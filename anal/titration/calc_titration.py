def detected_cpu_count() -> int:
    try:
        return max(1, len(os.sched_getaffinity(0)))
    except (AttributeError, OSError):
        return max(1, os.cpu_count() or 1)


def mean(xs: Sequence[float]) -> float:
    return sum(xs) / len(xs) if xs else math.nan


def stdev(xs: Sequence[float]) -> float:
    if len(xs) < 2:
        return math.nan
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def percentile_sorted(xs: Sequence[float], q: float) -> float:
    if not xs:
        return math.nan
    pos = (len(xs) - 1) * q
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return xs[lo]
    return xs[lo] * (hi - pos) + xs[hi] * (pos - lo)


def finite_or_none(value: float) -> Optional[float]:
    return float(value) if math.isfinite(value) else None


def sanitize_filename(text: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_.-]+", "_", text.strip())
    cleaned = cleaned.strip("._")
    return cleaned or "analysis"


def parse_ph_from_filename(path: str) -> float:
    base = os.path.basename(path)
    match = re.search(r"ph([0-9]+)_([0-9]+)", base)
    if not match:
        raise ValueError(f"Could not parse pH from filename: {path}")
    return float(f"{match.group(1)}.{match.group(2)}")


def parse_time_window(value: str) -> Tuple[float, float]:
    if ":" not in value:
        raise ValueError("Time window must look like START:END, e.g. 3:43")
    start, end = value.split(":", 1)
    return float(start), float(end)


def parse_int_list(value: str) -> List[int]:
    result: List[int] = []
    for token in value.split(","):
        token = token.strip()
        if token:
            result.append(int(token))
    return result


def parse_cutoff_pairs(value: str) -> List[Tuple[float, float]]:
    pairs: List[Tuple[float, float]] = []
    if not value.strip():
        return pairs
    for item in value.split(","):
        item = item.strip()
        if not item:
            continue
        if ":" not in item:
            raise ValueError(
                "Each cutoff sensitivity entry must look like LOW:HIGH, "
                "for example 0.1:0.9"
            )
        lo, hi = item.split(":", 1)
        low = float(lo)
        high = float(hi)
        if not (0.0 <= low < high <= 1.0):
            raise ValueError(f"Invalid lambda cutoffs: {item}")
        pairs.append((low, high))
    return pairs


def segment_ns(args: argparse.Namespace) -> float:
    return args.segment_steps * args.dt_ps / 1000.0


def block_ns_from_segments(args: argparse.Namespace, block_segments: int) -> float:
    return block_segments * segment_ns(args)


def route_output_path(
    requested: Optional[str],
    default_name: str,
    output_dir: Optional[Path],
) -> Path:
    """Route a path into output_dir while preserving only its basename."""
    if output_dir is None:
        return Path(requested) if requested else Path(default_name)
    name = Path(requested).name if requested else default_name
    return output_dir / name


def write_json(path: Path, payload: Mapping[str, object]) -> None:
    with path.open("w") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True, allow_nan=False)
        handle.write("\n")


def safe_log_probability(probability: float) -> float:
    return math.log(max(probability, 1.0e-300))


def logsumexp(values: Sequence[float]) -> float:
    maximum = max(values)
    return maximum + math.log(sum(math.exp(value - maximum) for value in values))


def summarize_samples(samples: Sequence[float]) -> Dict[str, Optional[float]]:
    finite = sorted(value for value in samples if math.isfinite(value))
    if not finite:
        return {
            "n": 0,
            "mean": None,
            "median": None,
            "sd": None,
            "ci95_low": None,
            "ci95_high": None,
        }
    return {
        "n": len(finite),
        "mean": mean(finite),
        "median": percentile_sorted(finite, 0.5),
        "sd": stdev(finite),
        "ci95_low": percentile_sorted(finite, 0.025),
        "ci95_high": percentile_sorted(finite, 0.975),
    }


