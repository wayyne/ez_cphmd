def run_coupled_mode(args: argparse.Namespace) -> int:
    output_dir = Path(args.coupled_output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    prefix_parts = [part for part in (args.run_label, args.primary_label, args.coupled_label) if part]
    prefix = sanitize_filename("_".join(prefix_parts))

    caches = load_coupled_caches(args.files, args)
    if not caches:
        print("Error: no readable files for coupled analysis", file=sys.stderr)
        return 1
    points = compute_coupled_points(caches, args.start_ns, args.end_ns, warn_empty=True)
    if len(points) < 3:
        print("Error: fewer than three valid pH points for coupled analysis", file=sys.stderr)
        return 1

    try:
        result = fit_complete_coupled_analysis(points, args)
    except Exception as error:
        print(f"Error: coupled analysis failed: {error}", file=sys.stderr)
        return 1

    curves = coupled_curve_sets(points, args.primary_label, args.coupled_label)
    all_curve_fits = {**result.marginal_fits, **result.conditional_fits}

    settings_payload = {
        "command": " ".join(sys.argv),
        "run_label": args.run_label,
        "primary_resid": args.resid,
        "primary_label": args.primary_label,
        "coupled_resid": args.coupled,
        "coupled_label": args.coupled_label,
        "time_window_ns": [args.start_ns, args.end_ns],
        "dt_ps": args.dt_ps,
        "segment_steps": args.segment_steps,
        "segment_ns": segment_ns(args),
        "lambda_stride_steps": args.lambda_stride_steps,
        "lambda_stride_ns": args.lambda_stride_steps * args.dt_ps / 1000.0,
        "lambda_cutoffs": [args.low, args.high],
        "fit_method": args.fit_method,
        "hill_mode": args.hill,
        "block_segments": parse_int_list(args.block_segments),
        "bootstrap_block_segments": args.bootstrap_block_segments,
        "bootstrap_block_ns": block_ns_from_segments(
            args, args.bootstrap_block_segments
        ),
        "nboot_requested": args.nboot,
        "seed": args.seed,
        "jobs": args.jobs if args.jobs > 0 else detected_cpu_count(),
        "temperature_k": args.temperature_k,
        "primary_pka_correction": args.primary_pka_correction,
        "coupled_pka_correction": args.coupled_pka_correction,
        "input_files": [str(Path(path)) for path in args.files],
    }
    write_json(output_dir / f"{prefix}_settings.json", settings_payload)

    frame_state_path = output_dir / f"{prefix}_frame_states.csv"
    frame_state_rows = write_coupled_frame_states_csv(
        frame_state_path,
        args.files,
        args,
    )

    write_joint_state_csv(output_dir / f"{prefix}_joint_states.csv", points, args)
    write_curve_csv(
        output_dir / f"{prefix}_marginal_and_conditional_curves.csv",
        curves,
        all_curve_fits,
        args.primary_pka_correction,
        args.coupled_pka_correction,
        args.primary_label,
        args.coupled_label,
    )
    write_macro_fit_csv(
        output_dir / f"{prefix}_macroscopic_fit.csv", points, result.macro
    )
    write_four_state_fit_csv(
        output_dir / f"{prefix}_four_state_model_comparison.csv",
        points,
        result.independent,
        result.interacting,
        args,
    )

    block_rows: List[Dict[str, object]] = []
    if args.stats in ("block-average", "both"):
        block_rows = coupled_block_rows(
            caches,
            args,
            args.start_ns,
            args.end_ns,
            parse_int_list(args.block_segments),
        )
        write_dict_rows(output_dir / f"{prefix}_block_fits.csv", block_rows)

    bootstrap_samples: List[Dict[str, float]] = []
    bootstrap_summary: Dict[str, Dict[str, Optional[float]]] = {}
    if args.stats in ("block-bootstrap", "both"):
        bootstrap_samples = coupled_block_bootstrap(
            caches, args, args.start_ns, args.end_ns
        )
        bootstrap_summary = write_bootstrap_outputs(
            output_dir / f"{prefix}_bootstrap_samples.csv",
            output_dir / f"{prefix}_bootstrap_summary.csv",
            bootstrap_samples,
        )

    convergence = coupled_convergence_rows(
        caches, args, args.start_ns, args.end_ns
    )
    if convergence:
        write_dict_rows(output_dir / f"{prefix}_convergence.csv", convergence)

    sensitivity = cutoff_sensitivity_rows(
        args.files, args, args.start_ns, args.end_ns
    )
    write_dict_rows(output_dir / f"{prefix}_cutoff_sensitivity.csv", sensitivity)

    summary_payload = complete_result_payload(
        result,
        args,
        points,
        bootstrap_summary=bootstrap_summary or None,
    )
    write_json(output_dir / f"{prefix}_summary.json", summary_payload)

    summary_row: Dict[str, object] = {
        "run_label": args.run_label,
        "primary_resid": args.resid,
        "primary_label": args.primary_label,
        "coupled_resid": args.coupled,
        "coupled_label": args.coupled_label,
    }
    summary_row.update(
        parameter_row_from_result(
            result,
            args.temperature_k,
            args.primary_pka_correction,
            args.coupled_pka_correction,
        )
    )
    write_dict_rows(output_dir / f"{prefix}_summary.csv", [summary_row])

    write_text_report(
        output_dir / f"{prefix}_report.txt",
        result,
        args,
        bootstrap_summary or None,
    )

    coupled_plots(
        output_dir,
        prefix,
        points,
        curves,
        result,
        convergence,
        bootstrap_samples,
        args,
    )

    print(f"Coupled analysis outputs written to: {output_dir.resolve()}")
    print(
        f"Frame-resolved coupled states: {frame_state_path} "
        f"({frame_state_rows} rows)"
    )
    print()
    print("Pair-level macroscopic stepwise pKa values:")
    print(f"  pK1, first protonation:  {result.macro.pk1_first:.6f}")
    print(f"  pK2, second protonation: {result.macro.pk2_second:.6f}")
    print()
    print("Residue-assigned conditional pKa values from the four-state model:")
    print(
        f"  {args.primary_label} | {args.coupled_label}H: "
        f"{result.interacting.primary_pka_partner_protonated:.6f}"
    )
    print(
        f"  {args.primary_label} | {args.coupled_label}-: "
        f"{result.interacting.primary_pka_partner_deprotonated:.6f}"
    )
    print(
        f"  {args.coupled_label} | {args.primary_label}H: "
        f"{result.interacting.coupled_pka_partner_protonated:.6f}"
    )
    print(
        f"  {args.coupled_label} | {args.primary_label}-: "
        f"{result.interacting.coupled_pka_partner_deprotonated:.6f}"
    )
    print(f"  coupling shift: {result.interacting.coupling_shift:.6f}")
    print()
    print(
        "Macroscopic pK1/pK2 are pair properties. The four conditional "
        "values above are the residue-specific assignments."
    )
    return 0


def run_ordinary_mode(args: argparse.Namespace) -> int:
    if args.his_resid is not None:
        caches = load_his_caches(args.files, args)
    else:
        if args.resid is None:
            print("Error: ordinary mode requires -R/--resid or -H/--his-resid", file=sys.stderr)
            return 1
        caches = load_residue_caches(args.files, args.resid, args)
    if not caches:
        print("Error: no readable lambda files", file=sys.stderr)
        return 1

    grouped = compute_grouped(
        caches, args, args.start_ns, args.end_ns, warn_empty=True
    )
    if not grouped:
        print("Error: no valid titration data", file=sys.stderr)
        return 1
    fits = fit_grouped(grouped, args.fit_method, args.hill)
    if not fits:
        print("Error: no titration curves could be fitted", file=sys.stderr)
        return 1

    data_path = route_output_path(None, "titcurve.dat", None)
    write_ordinary_data_file(data_path, grouped)
    if args.write_stats_csv:
        write_dict_rows(
            Path(args.write_stats_csv),
            ordinary_block_rows(caches, args, args.start_ns, args.end_ns),
        )
    if args.write_convergence_csv:
        write_dict_rows(
            Path(args.write_convergence_csv),
            ordinary_convergence_rows(caches, args, args.start_ns, args.end_ns),
        )
    ordinary_plot(Path(args.output) if args.output else None, grouped, fits)

    print(f"Saved pH/fraction data: {data_path}")
    for label, fit in sorted(fits.items()):
        print(f"{label}: pKa={fit.pka:.6f}, Hill={fit.hill:.6f}, npoints={fit.npoints}")
    return 0


