def coupled_convergence_rows(
    caches: Sequence[CachedLambdaFile],
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
) -> List[Dict[str, object]]:
    windows: List[Tuple[str, float, float]] = []
    if args.cumulative:
        current = start_ns + args.cumulative_step_ns
        while current <= end_ns + 1.0e-12:
            windows.append(("cumulative", start_ns, min(current, end_ns)))
            current += args.cumulative_step_ns
    if args.sliding_window_ns > 0.0:
        current = start_ns
        while current + args.sliding_window_ns <= end_ns + 1.0e-12:
            windows.append(
                ("sliding", current, current + args.sliding_window_ns)
            )
            current += args.sliding_step_ns

    rows: List[Dict[str, object]] = []
    for mode, window_start, window_end in windows:
        points = compute_coupled_points(caches, window_start, window_end)
        try:
            result = fit_coupled_core(points, args)
        except Exception:
            continue
        row: Dict[str, object] = {
            "mode": mode,
            "start_ns": window_start,
            "end_ns": window_end,
        }
        row.update(
            parameter_row_from_result(
                result,
                args.temperature_k,
                args.primary_pka_correction,
                args.coupled_pka_correction,
            )
        )
        rows.append(row)
    return rows


def cutoff_sensitivity_rows(
    files: Sequence[str],
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
) -> List[Dict[str, object]]:
    requested = parse_cutoff_pairs(args.coupled_cutoff_sensitivity)
    pairs: List[Tuple[float, float]] = [(args.low, args.high)]
    for pair in requested:
        if pair not in pairs:
            pairs.append(pair)

    rows: List[Dict[str, object]] = []
    for low, high in pairs:
        caches = load_coupled_caches(files, args, low=low, high=high)
        if not caches:
            continue
        points = compute_coupled_points(caches, start_ns, end_ns)
        try:
            result = fit_coupled_core(points, args)
        except Exception:
            continue
        total_clean = sum(point.clean_total for point in points)
        total_mixed = sum(point.mixed for point in points)
        row: Dict[str, object] = {
            "low_cutoff": low,
            "high_cutoff": high,
            "clean_frames": total_clean,
            "mixed_frames": total_mixed,
            "mixed_fraction": (
                total_mixed / (total_clean + total_mixed)
                if total_clean + total_mixed
                else math.nan
            ),
        }
        row.update(
            parameter_row_from_result(
                result,
                args.temperature_k,
                args.primary_pka_correction,
                args.coupled_pka_correction,
            )
        )
        rows.append(row)
    return rows


