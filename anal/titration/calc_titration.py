def write_curve_csv(
    path: Path,
    curves: Mapping[str, Sequence[CurvePoint]],
    fits: Mapping[str, FitResult],
    primary_correction: float,
    coupled_correction: float,
    primary_label: str,
    coupled_label: str,
) -> None:
    rows: List[Dict[str, object]] = []
    for label, points in curves.items():
        fit = fits.get(label)
        site_correction = 0.0
        if label.startswith(primary_label):
            site_correction = primary_correction
        elif label.startswith(coupled_label):
            site_correction = coupled_correction
        for point in points:
            rows.append(
                {
                    "curve": label,
                    "pH": point.ph,
                    "unprotonated_fraction": point.frac,
                    "protonated_count": point.prot,
                    "unprotonated_count": point.unprot,
                    "mixed_count": point.mixed,
                    "fit_pKa": fit.pka if fit else math.nan,
                    "corrected_fit_pKa": (
                        fit.pka + site_correction if fit else math.nan
                    ),
                    "fit_Hill": fit.hill if fit else math.nan,
                    "fit_objective": fit.objective if fit else math.nan,
                }
            )
    write_dict_rows(path, rows)


def write_macro_fit_csv(
    path: Path,
    points: Sequence[CoupledPoint],
    fit: MacroFitResult,
) -> None:
    rows: List[Dict[str, object]] = []
    for point in points:
        observed_total = point.clean_total
        observed = (
            point.both_deprotonated / observed_total,
            point.singly_protonated / observed_total,
            point.both_protonated / observed_total,
        )
        fitted = macroscopic_probabilities(
            point.ph, fit.pk1_first, fit.pk2_second
        )
        rows.append(
            {
                "pH": point.ph,
                "observed_P0": observed[0],
                "observed_P1": observed[1],
                "observed_P2": observed[2],
                "fitted_P0": fitted[0],
                "fitted_P1": fitted[1],
                "fitted_P2": fitted[2],
                "residual_P0": observed[0] - fitted[0],
                "residual_P1": observed[1] - fitted[1],
                "residual_P2": observed[2] - fitted[2],
                "pK1_first": fit.pk1_first,
                "pK2_second": fit.pk2_second,
            }
        )
    write_dict_rows(path, rows)


def write_four_state_fit_csv(
    path: Path,
    points: Sequence[CoupledPoint],
    independent: FourStateFitResult,
    interacting: FourStateFitResult,
    args: argparse.Namespace,
) -> None:
    rows: List[Dict[str, object]] = []
    state_names = (
        f"{args.primary_label}H/{args.coupled_label}H",
        f"{args.primary_label}-/{args.coupled_label}H",
        f"{args.primary_label}H/{args.coupled_label}-",
        f"{args.primary_label}-/{args.coupled_label}-",
    )
    for point in points:
        total = point.clean_total
        observed = (
            point.both_protonated / total,
            point.primary_deprotonated / total,
            point.coupled_deprotonated / total,
            point.both_deprotonated / total,
        )
        independent_probabilities = four_state_probabilities(
            point.ph,
            independent.primary_pka_partner_protonated,
            independent.coupled_pka_partner_protonated,
            0.0,
        )
        interacting_probabilities = four_state_probabilities(
            point.ph,
            interacting.primary_pka_partner_protonated,
            interacting.coupled_pka_partner_protonated,
            interacting.coupling_shift,
        )
        for state, obs, independent_pred, interacting_pred in zip(
            state_names,
            observed,
            independent_probabilities,
            interacting_probabilities,
        ):
            rows.append(
                {
                    "pH": point.ph,
                    "state": state,
                    "observed_probability": obs,
                    "independent_probability": independent_pred,
                    "interacting_probability": interacting_pred,
                    "independent_residual": obs - independent_pred,
                    "interacting_residual": obs - interacting_pred,
                }
            )
    write_dict_rows(path, rows)


def write_bootstrap_outputs(
    samples_path: Path,
    summary_path: Path,
    samples: Sequence[Mapping[str, float]],
) -> Dict[str, Dict[str, Optional[float]]]:
    write_dict_rows(samples_path, samples)
    summaries: Dict[str, Dict[str, Optional[float]]] = {}
    if samples:
        for key in samples[0]:
            summaries[key] = summarize_samples(
                [float(sample[key]) for sample in samples if key in sample]
            )
    rows = []
    for parameter, summary in summaries.items():
        row: Dict[str, object] = {"parameter": parameter}
        row.update(summary)
        rows.append(row)
    write_dict_rows(summary_path, rows)
    return summaries


