def coupled_block_rows(
    caches: Sequence[CachedLambdaFile],
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
    block_segments_list: Sequence[int],
) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for block_segments in block_segments_list:
        block_length = block_ns_from_segments(args, block_segments)
        blocks = coupled_blocks(caches, start_ns, end_ns, block_length)
        for index, points in enumerate(blocks):
            try:
                result = fit_coupled_core(points, args)
            except Exception:
                continue
            row: Dict[str, object] = {
                "block_segments": block_segments,
                "block_ns": block_length,
                "block_index": index,
                "start_ns": start_ns + index * block_length,
                "end_ns": start_ns + (index + 1) * block_length,
            }
            row.update(
                parameter_row_from_result(
                    result,
                    args.temperature_k,
                    args.primary_pka_correction,
                    args.coupled_pka_correction,
                )
            )
            rows.append(row)
    return rows


def compact_coupled_bootstrap_data(
    blocks: Sequence[Sequence[CoupledPoint]],
) -> CoupledBootstrapData:
    ph_values = sorted(
        {round(point.ph, 6): point.ph for block in blocks for point in block}.values()
    )
    ph_index = {round(ph, 6): index for index, ph in enumerate(ph_values)}
    nph = len(ph_values)
    compact_blocks: List[Tuple[int, ...]] = []
    for block in blocks:
        counts = [[0] * nph for _ in range(5)]
        for point in block:
            index = ph_index[round(point.ph, 6)]
            counts[0][index] += point.both_protonated
            counts[1][index] += point.primary_deprotonated
            counts[2][index] += point.coupled_deprotonated
            counts[3][index] += point.both_deprotonated
            counts[4][index] += point.mixed
        compact_blocks.append(tuple(value for array in counts for value in array))
    return CoupledBootstrapData(tuple(ph_values), tuple(compact_blocks))


def _coupled_bootstrap_worker_init(
    data: CoupledBootstrapData,
    temperature_k: float,
    primary_correction: float,
    coupled_correction: float,
) -> None:
    global _COUPLED_BOOTSTRAP_DATA
    global _COUPLED_BOOTSTRAP_TEMPERATURE_K
    global _COUPLED_BOOTSTRAP_PRIMARY_CORRECTION
    global _COUPLED_BOOTSTRAP_COUPLED_CORRECTION
    _COUPLED_BOOTSTRAP_DATA = data
    _COUPLED_BOOTSTRAP_TEMPERATURE_K = temperature_k
    _COUPLED_BOOTSTRAP_PRIMARY_CORRECTION = primary_correction
    _COUPLED_BOOTSTRAP_COUPLED_CORRECTION = coupled_correction


def _points_from_compact_counts(
    ph_values: Sequence[float],
    counts: Sequence[Sequence[int]],
) -> List[CoupledPoint]:
    points: List[CoupledPoint] = []
    for index, ph in enumerate(ph_values):
        point = CoupledPoint(
            ph=ph,
            both_protonated=counts[0][index],
            primary_deprotonated=counts[1][index],
            coupled_deprotonated=counts[2][index],
            both_deprotonated=counts[3][index],
            mixed=counts[4][index],
        )
        if point.clean_total > 0:
            points.append(point)
    return points


def _bootstrap_parameter_row(points: Sequence[CoupledPoint]) -> Optional[Dict[str, float]]:
    try:
        macro = fit_macroscopic(points)
        independent = fit_four_state(points, interacting=False)
        interacting = fit_four_state(
            points,
            interacting=True,
            initial_primary_pka=independent.primary_pka_partner_protonated,
            initial_coupled_pka=independent.coupled_pka_partner_protonated,
        )
    except Exception:
        return None

    empirical_primary, empirical_coupled = empirical_p1_carrier_fractions(points)
    fitted_primary, fitted_coupled = fitted_p1_carrier_fractions(interacting)
    derived_pk1, derived_pk2 = derived_macroscopic_from_four_state(interacting)
    corrected_pk1, corrected_pk2 = derived_macroscopic_from_four_state(
        interacting,
        _COUPLED_BOOTSTRAP_PRIMARY_CORRECTION,
        _COUPLED_BOOTSTRAP_COUPLED_CORRECTION,
    )
    return {
        "macro_pK1_first": macro.pk1_first,
        "macro_pK2_second": macro.pk2_second,
        "primary_pKa_partner_protonated": interacting.primary_pka_partner_protonated,
        "primary_pKa_partner_deprotonated": interacting.primary_pka_partner_deprotonated,
        "coupled_pKa_partner_protonated": interacting.coupled_pka_partner_protonated,
        "coupled_pKa_partner_deprotonated": interacting.coupled_pka_partner_deprotonated,
        "coupling_shift_pKa": interacting.coupling_shift,
        "coupling_free_energy_kcal_mol": coupling_free_energy_kcal_mol(
            interacting.coupling_shift, _COUPLED_BOOTSTRAP_TEMPERATURE_K
        ),
        "derived_macro_pK1_first": derived_pk1,
        "derived_macro_pK2_second": derived_pk2,
        "corrected_primary_pKa_partner_protonated": (
            interacting.primary_pka_partner_protonated
            + _COUPLED_BOOTSTRAP_PRIMARY_CORRECTION
        ),
        "corrected_primary_pKa_partner_deprotonated": (
            interacting.primary_pka_partner_deprotonated
            + _COUPLED_BOOTSTRAP_PRIMARY_CORRECTION
        ),
        "corrected_coupled_pKa_partner_protonated": (
            interacting.coupled_pka_partner_protonated
            + _COUPLED_BOOTSTRAP_COUPLED_CORRECTION
        ),
        "corrected_coupled_pKa_partner_deprotonated": (
            interacting.coupled_pka_partner_deprotonated
            + _COUPLED_BOOTSTRAP_COUPLED_CORRECTION
        ),
        "corrected_derived_macro_pK1_first": corrected_pk1,
        "corrected_derived_macro_pK2_second": corrected_pk2,
        "delta_AIC_independent_minus_interacting": independent.aic - interacting.aic,
        "likelihood_ratio_statistic": 2.0
        * (independent.neg_log_likelihood - interacting.neg_log_likelihood),
        "fitted_primary_protonated_fraction_in_P1": fitted_primary,
        "fitted_coupled_protonated_fraction_in_P1": fitted_coupled,
        "empirical_primary_protonated_fraction_in_P1": empirical_primary,
        "empirical_coupled_protonated_fraction_in_P1": empirical_coupled,
    }


def _coupled_bootstrap_worker_task(
    seeds: Tuple[int, ...],
) -> List[Dict[str, float]]:
    if _COUPLED_BOOTSTRAP_DATA is None:
        raise RuntimeError("Coupled bootstrap worker was not initialized")
    data = _COUPLED_BOOTSTRAP_DATA
    nblocks = len(data.blocks)
    nph = len(data.ph_values)
    rows: List[Dict[str, float]] = []

    for seed in seeds:
        rng = random.Random(seed)
        multiplicities = [0] * nblocks
        for _ in range(nblocks):
            multiplicities[rng.randrange(nblocks)] += 1

        counts = [[0] * nph for _ in range(5)]
        for block_index, multiplier in enumerate(multiplicities):
            if multiplier == 0:
                continue
            block = data.blocks[block_index]
            for state in range(5):
                offset = state * nph
                for ph_index in range(nph):
                    counts[state][ph_index] += block[offset + ph_index] * multiplier

        points = _points_from_compact_counts(data.ph_values, counts)
        row = _bootstrap_parameter_row(points)
        if row is not None:
            rows.append(row)
    return rows


def chunked(values: Sequence[int], size: int) -> Iterable[Tuple[int, ...]]:
    for start in range(0, len(values), size):
        yield tuple(values[start : start + size])


def coupled_block_bootstrap(
    caches: Sequence[CachedLambdaFile],
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
) -> List[Dict[str, float]]:
    block_length = block_ns_from_segments(args, args.bootstrap_block_segments)
    blocks = coupled_blocks(caches, start_ns, end_ns, block_length)
    if len(blocks) < 2:
        return []
    data = compact_coupled_bootstrap_data(blocks)

    jobs = args.jobs if args.jobs > 0 else detected_cpu_count()
    jobs = max(1, min(jobs, args.nboot))
    master_rng = random.Random(args.seed)
    seeds = [master_rng.getrandbits(64) for _ in range(args.nboot)]
    tasks = list(chunked(seeds, args.bootstrap_chunk_size))
    rows: List[Dict[str, float]] = []

    if jobs == 1:
        _coupled_bootstrap_worker_init(
            data,
            args.temperature_k,
            args.primary_pka_correction,
            args.coupled_pka_correction,
        )
        for task in tasks:
            rows.extend(_coupled_bootstrap_worker_task(task))
    else:
        with ProcessPoolExecutor(
            max_workers=jobs,
            initializer=_coupled_bootstrap_worker_init,
            initargs=(
                data,
                args.temperature_k,
                args.primary_pka_correction,
                args.coupled_pka_correction,
            ),
        ) as executor:
            for result_rows in executor.map(
                _coupled_bootstrap_worker_task, tasks, chunksize=1
            ):
                rows.extend(result_rows)
    return rows


