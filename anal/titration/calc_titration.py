def coupled_blocks(
    caches: Sequence[CachedLambdaFile],
    start_ns: float,
    end_ns: float,
    block_ns: float,
) -> List[List[CoupledPoint]]:
    nblocks = int(math.floor((end_ns - start_ns) / block_ns))
    blocks: List[List[CoupledPoint]] = []
    for index in range(nblocks):
        block_start = start_ns + index * block_ns
        block_end = block_start + block_ns
        points = compute_coupled_points(caches, block_start, block_end)
        if points:
            blocks.append(points)
    return blocks


def aggregate_coupled_point_sets(
    point_sets: Sequence[Sequence[CoupledPoint]],
) -> List[CoupledPoint]:
    accumulator: Dict[float, CoupledPoint] = {}
    for points in point_sets:
        for point in points:
            key = round(point.ph, 6)
            if key not in accumulator:
                accumulator[key] = CoupledPoint(**asdict(point))
            else:
                accumulator[key] = add_coupled_points(accumulator[key], point)
    return sorted(accumulator.values(), key=lambda point: point.ph)


