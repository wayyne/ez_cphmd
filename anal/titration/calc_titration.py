def write_dict_rows(path: Path, rows: Sequence[Mapping[str, object]]) -> None:
    if not rows:
        return
    fieldnames: List[str] = []
    seen = set()
    for row in rows:
        for key in row:
            if key not in seen:
                fieldnames.append(key)
                seen.add(key)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def write_coupled_frame_states_csv(
    path: Path,
    files: Sequence[str],
    args: argparse.Namespace,
) -> int:
    """
    Write one row per lambda observation in the requested analysis window.

    This file is intended for joining protonation-state assignments to
    coordinate frames for state-conditioned structural analysis.

    The state definition is identical to that used by build_coupled_cache()
    and therefore to the coupled-titration analysis itself.
    """
    fieldnames = [
        "source_file",
        "slot_label",
        "pH",
        "sample_index",
        "step",
        "absolute_time_ns",
        "relative_step",
        "time_ns",
        "primary_resid",
        "primary_label",
        "primary_lambda",
        "primary_state",
        "coupled_resid",
        "coupled_label",
        "coupled_lambda",
        "coupled_state",
        "state_code",
        "state_label",
        "clean",
    ]

    rows_written = 0

    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()

        for source_file in files:
            try:
                ph = parse_ph_from_filename(source_file)
                ires, itauto, data = read_lambda_lines(source_file)

                primary_column = select_protonation_column(
                    ires,
                    itauto,
                    args.resid,
                )
                coupled_column = select_protonation_column(
                    ires,
                    itauto,
                    args.coupled,
                )

                if primary_column is None:
                    raise RuntimeError(
                        f"Could not find primary residue {args.resid}"
                    )
                if coupled_column is None:
                    raise RuntimeError(
                        f"Could not find coupled residue {args.coupled}"
                    )
                if primary_column == coupled_column:
                    raise RuntimeError(
                        "Primary and coupled residue columns are identical"
                    )

                first_step: Optional[float] = None
                sample_index = 0

                for parts in data:
                    if len(parts) <= max(primary_column, coupled_column):
                        continue

                    try:
                        step = float(parts[0])
                        primary_lambda = float(parts[primary_column])
                        coupled_lambda = float(parts[coupled_column])
                    except ValueError:
                        continue

                    if first_step is None:
                        first_step = step

                    sample_index += 1

                    relative_step = step - first_step
                    absolute_time_ns = step * args.dt_ps / 1000.0
                    time_ns = relative_step * args.dt_ps / 1000.0

                    # Match the [start, end) convention used by
                    # _window_counts()/bisect_left in the coupled analysis.
                    if time_ns < args.start_ns or time_ns >= args.end_ns:
                        continue

                    code = classify_coupled_state(
                        primary_lambda,
                        coupled_lambda,
                        args.low,
                        args.high,
                    )

                    primary_state = (
                        "H"
                        if primary_lambda <= args.low
                        else "-"
                        if primary_lambda >= args.high
                        else "mixed"
                    )
                    coupled_state = (
                        "H"
                        if coupled_lambda <= args.low
                        else "-"
                        if coupled_lambda >= args.high
                        else "mixed"
                    )

                    writer.writerow(
                        {
                            "source_file": Path(source_file).name,
                            "slot_label": Path(source_file).stem,
                            "pH": ph,
                            "sample_index": sample_index,
                            "step": (
                                int(step)
                                if step.is_integer()
                                else f"{step:.10g}"
                            ),
                            "absolute_time_ns": f"{absolute_time_ns:.10g}",
                            "relative_step": (
                                int(relative_step)
                                if relative_step.is_integer()
                                else f"{relative_step:.10g}"
                            ),
                            "time_ns": f"{time_ns:.10g}",
                            "primary_resid": args.resid,
                            "primary_label": args.primary_label,
                            "primary_lambda": f"{primary_lambda:.10g}",
                            "primary_state": primary_state,
                            "coupled_resid": args.coupled,
                            "coupled_label": args.coupled_label,
                            "coupled_lambda": f"{coupled_lambda:.10g}",
                            "coupled_state": coupled_state,
                            "state_code": code,
                            "state_label": coupled_state_label(
                                code,
                                args.primary_label,
                                args.coupled_label,
                            ),
                            "clean": int(code != 4),
                        }
                    )
                    rows_written += 1

            except Exception as error:
                print(
                    f"Warning: could not write frame-state assignments for "
                    f"{source_file}: {error}",
                    file=sys.stderr,
                )

    return rows_written

