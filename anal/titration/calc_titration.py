@dataclass
class CurvePoint:
    label: str
    ph: float
    frac: float
    prot: int
    unprot: int
    mixed: int = 0

    @property
    def clean_total(self) -> int:
        return self.prot + self.unprot


@dataclass
class FitResult:
    pka: float
    hill: float
    npoints: int
    objective: float
    method: str = "nonlinear-hh"


@dataclass(frozen=True)
class CachedLambdaFile:
    path: str
    ph: float
    mode: str
    times_ns: Tuple[float, ...]
    prefixes: Tuple[Tuple[int, ...], ...]


@dataclass
class CoupledPoint:
    ph: float
    both_protonated: int
    primary_deprotonated: int
    coupled_deprotonated: int
    both_deprotonated: int
    mixed: int

    @property
    def singly_protonated(self) -> int:
        return self.primary_deprotonated + self.coupled_deprotonated

    @property
    def clean_total(self) -> int:
        return (
            self.both_protonated
            + self.primary_deprotonated
            + self.coupled_deprotonated
            + self.both_deprotonated
        )

    @property
    def mean_bound_protons(self) -> float:
        if self.clean_total == 0:
            return math.nan
        return (
            2.0 * self.both_protonated + self.singly_protonated
        ) / self.clean_total

    @property
    def mixed_fraction(self) -> float:
        total = self.clean_total + self.mixed
        return self.mixed / total if total else math.nan


@dataclass
class MacroFitResult:
    pk1_first: float
    pk2_second: float
    npoints: int
    nframes: int
    neg_log_likelihood: float
    method: str = "macroscopic-three-state-multinomial"


@dataclass
class FourStateFitResult:
    model: str
    primary_pka_partner_protonated: float
    coupled_pka_partner_protonated: float
    coupling_shift: float
    npoints: int
    nframes: int
    neg_log_likelihood: float
    aic: float
    converged: bool

    @property
    def primary_pka_partner_deprotonated(self) -> float:
        return self.primary_pka_partner_protonated + self.coupling_shift

    @property
    def coupled_pka_partner_deprotonated(self) -> float:
        return self.coupled_pka_partner_protonated + self.coupling_shift


@dataclass
class CoupledFullResult:
    macro: MacroFitResult
    independent: FourStateFitResult
    interacting: FourStateFitResult
    marginal_fits: Dict[str, FitResult]
    conditional_fits: Dict[str, FitResult]
    empirical_primary_protonated_fraction_in_p1: float
    empirical_coupled_protonated_fraction_in_p1: float
    fitted_primary_protonated_fraction_in_p1: float
    fitted_coupled_protonated_fraction_in_p1: float
    assignment: str
    delta_aic_independent_minus_interacting: float
    likelihood_ratio_statistic: float


