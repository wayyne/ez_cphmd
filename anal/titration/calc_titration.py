def points_from_cache(
    cache: CachedLambdaFile,
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
    label: str = "DATA",
) -> List[CurvePoint]:
    counts = _window_counts(cache, start_ns, end_ns)
    if cache.mode == "normal":
        protonated, unprotonated, mixed = counts
        denominator = protonated + unprotonated
        if denominator == 0:
            return []
        return [
            CurvePoint(
                label,
                cache.ph,
                unprotonated / denominator,
                protonated,
                unprotonated,
                mixed,
            )
        ]

    protonated, chi_low, chi_high, mixed_chi, mixed_lambda = counts
    neutral = chi_low + chi_high + mixed_chi
    points: List[CurvePoint] = []
    macro_denominator = protonated + neutral
    if macro_denominator > 0:
        points.append(
            CurvePoint(
                "HIS",
                cache.ph,
                neutral / macro_denominator,
                protonated,
                neutral,
                mixed_lambda,
            )
        )

    hid_count, hie_count = (
        (chi_low, chi_high) if args.his_map == "hid-low" else (chi_high, chi_low)
    )
    hid_denominator = protonated + hid_count
    hie_denominator = protonated + hie_count
    if hid_denominator > 0:
        points.append(
            CurvePoint(
                "HID",
                cache.ph,
                hid_count / hid_denominator,
                protonated,
                hid_count,
                mixed_chi,
            )
        )
    if hie_denominator > 0:
        points.append(
            CurvePoint(
                "HIE",
                cache.ph,
                hie_count / hie_denominator,
                protonated,
                hie_count,
                mixed_chi,
            )
        )
    return points


def add_curve_points(a: CurvePoint, b: CurvePoint) -> CurvePoint:
    if a.label != b.label or abs(a.ph - b.ph) > 1.0e-6:
        raise ValueError("Cannot add incompatible CurvePoint objects")
    protonated = a.prot + b.prot
    unprotonated = a.unprot + b.unprot
    mixed = a.mixed + b.mixed
    denominator = protonated + unprotonated
    return CurvePoint(
        a.label,
        a.ph,
        unprotonated / denominator if denominator else math.nan,
        protonated,
        unprotonated,
        mixed,
    )


def aggregate_curve_points(points: Iterable[CurvePoint]) -> List[CurvePoint]:
    accumulator: Dict[Tuple[str, float], CurvePoint] = {}
    for point in points:
        key = (point.label, round(point.ph, 6))
        if key not in accumulator:
            accumulator[key] = point
        else:
            accumulator[key] = add_curve_points(accumulator[key], point)
    return sorted(accumulator.values(), key=lambda point: (point.label, point.ph))


def compute_grouped(
    caches: Sequence[CachedLambdaFile],
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
    label: str = "DATA",
    warn_empty: bool = False,
) -> Dict[str, List[CurvePoint]]:
    grouped: Dict[str, List[CurvePoint]] = {}
    for cache in caches:
        points = points_from_cache(cache, args, start_ns, end_ns, label=label)
        if not points:
            if warn_empty:
                print(
                    f"Warning: no clean states in {start_ns}:{end_ns} ns for {cache.path}",
                    file=sys.stderr,
                )
            continue
        for point in points:
            grouped.setdefault(point.label, []).append(point)
    for curve_label in list(grouped):
        grouped[curve_label] = aggregate_curve_points(grouped[curve_label])
    return grouped


# -----------------------------------------------------------------------------
# Henderson-Hasselbalch fitting
# -----------------------------------------------------------------------------


def hh_function(ph: float, pka: float, hill: float) -> float:
    exponent = hill * (pka - ph)
    if exponent > 300:
        return 0.0
    if exponent < -300:
        return 1.0
    return 1.0 / (1.0 + 10.0**exponent)


def fit_hh_logit(points: Sequence[CurvePoint]) -> FitResult:
    x_values: List[float] = []
    y_values: List[float] = []
    for point in points:
        denominator = point.clean_total
        if denominator <= 0:
            continue
        adjusted = (point.unprot + 0.5) / (denominator + 1.0)
        adjusted = min(max(adjusted, 1.0e-12), 1.0 - 1.0e-12)
        y_values.append(math.log10((1.0 / adjusted) - 1.0))
        x_values.append(point.ph)
    if len(x_values) < 3:
        raise RuntimeError("Fewer than three valid pH points for HH fitting")
    x_mean = mean(x_values)
    y_mean = mean(y_values)
    sxx = sum((value - x_mean) ** 2 for value in x_values)
    sxy = sum(
        (x - x_mean) * (y - y_mean) for x, y in zip(x_values, y_values)
    )
    if sxx == 0.0:
        raise RuntimeError("Cannot fit HH curve because all pH values are identical")
    slope = sxy / sxx
    intercept = y_mean - slope * x_mean
    hill = -slope
    if abs(hill) < 1.0e-12:
        raise RuntimeError("Fitted Hill coefficient is approximately zero")
    pka = intercept / hill
    objective = hh_weighted_sse(points, pka, hill, "free")
    return FitResult(pka, hill, len(x_values), objective, "logit")


def hh_weighted_sse(
    points: Sequence[CurvePoint],
    pka: float,
    hill: float,
    hill_mode: str,
) -> float:
    total = 0.0
    effective_hill = 1.0 if hill_mode == "fixed1" else hill
    for point in points:
        denominator = point.clean_total
        if denominator <= 0:
            continue
        observed = (point.unprot + 0.5) / (denominator + 1.0)
        predicted = hh_function(point.ph, pka, effective_hill)
        variance = max(
            observed * (1.0 - observed) / denominator,
            1.0 / ((denominator + 1.0) ** 2),
        )
        total += ((observed - predicted) ** 2) / variance
    return total


def fit_hh_nonlinear(
    points: Sequence[CurvePoint],
    hill_mode: str = "free",
) -> FitResult:
    valid = [point for point in points if point.clean_total > 0]
    if len(valid) < 3:
        raise RuntimeError("Fewer than three valid pH points for HH fitting")

    try:
        start = fit_hh_logit(valid)
        starting_pka = start.pka
        starting_hill = max(0.05, min(5.0, start.hill))
    except Exception:
        starting_pka = mean([point.ph for point in valid])
        starting_hill = 1.0

    try:
        from scipy.optimize import minimize

        if hill_mode == "fixed1":
            result = minimize(
                lambda values: hh_weighted_sse(valid, float(values[0]), 1.0, hill_mode),
                [starting_pka],
                method="Nelder-Mead",
                options={"maxiter": 10000, "xatol": 1.0e-10, "fatol": 1.0e-8},
            )
            pka = float(result.x[0])
            hill = 1.0
        else:
            def objective(values: Sequence[float]) -> float:
                pka = float(values[0])
                hill = float(values[1])
                if hill <= 0.0 or hill > 10.0:
                    return 1.0e100
                return hh_weighted_sse(valid, pka, hill, hill_mode)

            result = minimize(
                objective,
                [starting_pka, starting_hill],
                method="Nelder-Mead",
                options={"maxiter": 10000, "xatol": 1.0e-10, "fatol": 1.0e-8},
            )
            pka = float(result.x[0])
            hill = float(result.x[1])
        return FitResult(
            pka,
            hill,
            len(valid),
            hh_weighted_sse(valid, pka, hill, hill_mode),
            "nonlinear-hh",
        )
    except Exception:
        ph_min = min(point.ph for point in valid) - 2.0
        ph_max = max(point.ph for point in valid) + 2.0
        best = (
            hh_weighted_sse(valid, starting_pka, starting_hill, hill_mode),
            starting_pka,
            starting_hill,
        )
        pka_step = max(0.5, 0.25 * (ph_max - ph_min))
        hill_step = 0.5
        for _ in range(18):
            pka_candidates = [best[1] + offset * pka_step for offset in range(-5, 6)]
            if hill_mode == "fixed1":
                hill_candidates = [1.0]
            else:
                hill_candidates = [
                    max(0.02, best[2] + offset * hill_step)
                    for offset in range(-5, 6)
                ]
            for pka in pka_candidates:
                for hill in hill_candidates:
                    value = hh_weighted_sse(valid, pka, hill, hill_mode)
                    if value < best[0]:
                        best = (value, pka, hill)
            pka_step *= 0.5
            hill_step *= 0.5
        return FitResult(
            best[1],
            1.0 if hill_mode == "fixed1" else best[2],
            len(valid),
            best[0],
            "nonlinear-hh-grid",
        )


def fit_hh(
    points: Sequence[CurvePoint],
    fit_method: str,
    hill_mode: str,
) -> FitResult:
    if fit_method == "logit":
        if hill_mode == "fixed1":
            return fit_hh_nonlinear(points, "fixed1")
        return fit_hh_logit(points)
    if fit_method == "nonlinear-hh":
        return fit_hh_nonlinear(points, hill_mode)
    raise RuntimeError(f"Unknown HH fit method: {fit_method}")


def fit_grouped(
    grouped: Mapping[str, Sequence[CurvePoint]],
    fit_method: str,
    hill_mode: str,
) -> Dict[str, FitResult]:
    fits: Dict[str, FitResult] = {}
    for label, points in sorted(grouped.items()):
        if len(points) < 3:
            continue
        try:
            fits[label] = fit_hh(points, fit_method, hill_mode)
        except Exception:
            continue
    return fits


