def coupled_point_from_cache(
    cache: CachedLambdaFile,
    start_ns: float,
    end_ns: float,
) -> Optional[CoupledPoint]:
    if cache.mode != "coupled":
        raise ValueError("Expected coupled cache")
    hh, primary_deprotonated, coupled_deprotonated, dd, mixed = _window_counts(
        cache, start_ns, end_ns
    )
    point = CoupledPoint(
        cache.ph,
        hh,
        primary_deprotonated,
        coupled_deprotonated,
        dd,
        mixed,
    )
    return point if point.clean_total > 0 else None


def add_coupled_points(a: CoupledPoint, b: CoupledPoint) -> CoupledPoint:
    if abs(a.ph - b.ph) > 1.0e-6:
        raise ValueError("Cannot add coupled points at different pH values")
    return CoupledPoint(
        ph=a.ph,
        both_protonated=a.both_protonated + b.both_protonated,
        primary_deprotonated=a.primary_deprotonated + b.primary_deprotonated,
        coupled_deprotonated=a.coupled_deprotonated + b.coupled_deprotonated,
        both_deprotonated=a.both_deprotonated + b.both_deprotonated,
        mixed=a.mixed + b.mixed,
    )


def compute_coupled_points(
    caches: Sequence[CachedLambdaFile],
    start_ns: float,
    end_ns: float,
    warn_empty: bool = False,
) -> List[CoupledPoint]:
    accumulator: Dict[float, CoupledPoint] = {}
    for cache in caches:
        point = coupled_point_from_cache(cache, start_ns, end_ns)
        if point is None:
            if warn_empty:
                print(
                    f"Warning: no clean coupled states in {start_ns}:{end_ns} ns "
                    f"for {cache.path}",
                    file=sys.stderr,
                )
            continue
        key = round(point.ph, 6)
        if key not in accumulator:
            accumulator[key] = point
        else:
            accumulator[key] = add_coupled_points(accumulator[key], point)
    return sorted(accumulator.values(), key=lambda point: point.ph)


def coupled_curve_sets(
    points: Sequence[CoupledPoint],
    primary_label: str,
    coupled_label: str,
) -> Dict[str, List[CurvePoint]]:
    """Construct marginal and partner-conditioned titration curves."""
    curves: Dict[str, List[CurvePoint]] = {
        f"{primary_label}_marginal": [],
        f"{coupled_label}_marginal": [],
        f"{primary_label}|{coupled_label}H": [],
        f"{primary_label}|{coupled_label}-": [],
        f"{coupled_label}|{primary_label}H": [],
        f"{coupled_label}|{primary_label}-": [],
    }

    for point in points:
        # Marginal primary titration.
        primary_protonated = point.both_protonated + point.coupled_deprotonated
        primary_unprotonated = point.primary_deprotonated + point.both_deprotonated
        denominator = primary_protonated + primary_unprotonated
        if denominator:
            curves[f"{primary_label}_marginal"].append(
                CurvePoint(
                    f"{primary_label}_marginal",
                    point.ph,
                    primary_unprotonated / denominator,
                    primary_protonated,
                    primary_unprotonated,
                    point.mixed,
                )
            )

        # Marginal coupled titration.
        coupled_protonated = point.both_protonated + point.primary_deprotonated
        coupled_unprotonated = point.coupled_deprotonated + point.both_deprotonated
        denominator = coupled_protonated + coupled_unprotonated
        if denominator:
            curves[f"{coupled_label}_marginal"].append(
                CurvePoint(
                    f"{coupled_label}_marginal",
                    point.ph,
                    coupled_unprotonated / denominator,
                    coupled_protonated,
                    coupled_unprotonated,
                    point.mixed,
                )
            )

        # Primary titration conditional on coupled residue protonated.
        denominator = point.both_protonated + point.primary_deprotonated
        if denominator:
            curves[f"{primary_label}|{coupled_label}H"].append(
                CurvePoint(
                    f"{primary_label}|{coupled_label}H",
                    point.ph,
                    point.primary_deprotonated / denominator,
                    point.both_protonated,
                    point.primary_deprotonated,
                    point.mixed,
                )
            )

        # Primary titration conditional on coupled residue deprotonated.
        denominator = point.coupled_deprotonated + point.both_deprotonated
        if denominator:
            curves[f"{primary_label}|{coupled_label}-"].append(
                CurvePoint(
                    f"{primary_label}|{coupled_label}-",
                    point.ph,
                    point.both_deprotonated / denominator,
                    point.coupled_deprotonated,
                    point.both_deprotonated,
                    point.mixed,
                )
            )

        # Coupled titration conditional on primary residue protonated.
        denominator = point.both_protonated + point.coupled_deprotonated
        if denominator:
            curves[f"{coupled_label}|{primary_label}H"].append(
                CurvePoint(
                    f"{coupled_label}|{primary_label}H",
                    point.ph,
                    point.coupled_deprotonated / denominator,
                    point.both_protonated,
                    point.coupled_deprotonated,
                    point.mixed,
                )
            )

        # Coupled titration conditional on primary residue deprotonated.
        denominator = point.primary_deprotonated + point.both_deprotonated
        if denominator:
            curves[f"{coupled_label}|{primary_label}-"].append(
                CurvePoint(
                    f"{coupled_label}|{primary_label}-",
                    point.ph,
                    point.both_deprotonated / denominator,
                    point.primary_deprotonated,
                    point.both_deprotonated,
                    point.mixed,
                )
            )

    return curves


# -----------------------------------------------------------------------------
# Macroscopic stepwise two-proton model
# -----------------------------------------------------------------------------


def macroscopic_probabilities(
    ph: float,
    pk1_first: float,
    pk2_second: float,
) -> Tuple[float, float, float]:
    """
    Return P0, P1, P2 for zero, one, and two bound protons.

    This follows Henderson et al. (2020):
      P0 = 1/Z
      P1 = 10^(pK1-pH)/Z
      P2 = 10^(pK1+pK2-2pH)/Z

    pK1 is the first protonation event from the doubly deprotonated pair;
    pK2 is the second protonation event.  The fit enforces pK1 >= pK2.
    """
    natural_log_10 = math.log(10.0)
    log_weights = (
        0.0,
        natural_log_10 * (pk1_first - ph),
        natural_log_10 * (pk1_first + pk2_second - 2.0 * ph),
    )
    normalization = logsumexp(log_weights)
    return tuple(math.exp(value - normalization) for value in log_weights)  # type: ignore[return-value]


def macroscopic_nll(
    points: Sequence[CoupledPoint],
    pk1_first: float,
    pk2_second: float,
) -> float:
    if pk1_first < pk2_second:
        return 1.0e100 + 1.0e6 * (pk2_second - pk1_first)
    nll = 0.0
    for point in points:
        p0, p1, p2 = macroscopic_probabilities(point.ph, pk1_first, pk2_second)
        counts = (
            point.both_deprotonated,
            point.singly_protonated,
            point.both_protonated,
        )
        probabilities = (p0, p1, p2)
        nll -= sum(
            count * safe_log_probability(probability)
            for count, probability in zip(counts, probabilities)
        )
    return nll


def fit_macroscopic(points: Sequence[CoupledPoint]) -> MacroFitResult:
    valid = [point for point in points if point.clean_total > 0]
    if len(valid) < 3:
        raise RuntimeError("Fewer than three valid pH points for macroscopic fit")
    ph_min = min(point.ph for point in valid)
    ph_max = max(point.ph for point in valid)
    center_start = 0.5 * (ph_min + ph_max)
    gap_start = 1.0

    try:
        from scipy.optimize import minimize

        def objective(values: Sequence[float]) -> float:
            center = float(values[0])
            gap = math.exp(float(values[1]))
            return macroscopic_nll(valid, center + 0.5 * gap, center - 0.5 * gap)

        result = minimize(
            objective,
            [center_start, math.log(gap_start)],
            method="Nelder-Mead",
            options={"maxiter": 20000, "xatol": 1.0e-10, "fatol": 1.0e-8},
        )
        center = float(result.x[0])
        gap = math.exp(float(result.x[1]))
        pk1_first = center + 0.5 * gap
        pk2_second = center - 0.5 * gap
    except Exception:
        best = (math.inf, center_start + 0.5, center_start - 0.5)
        step = 0.25
        lower = ph_min - 4.0
        upper = ph_max + 4.0
        first = lower
        while first <= upper + 1.0e-12:
            second = lower
            while second <= first + 1.0e-12:
                value = macroscopic_nll(valid, first, second)
                if value < best[0]:
                    best = (value, first, second)
                second += step
            first += step
        for _ in range(16):
            for first_candidate in [best[1] + offset * step for offset in range(-4, 5)]:
                for second_candidate in [best[2] + offset * step for offset in range(-4, 5)]:
                    if first_candidate < second_candidate:
                        continue
                    value = macroscopic_nll(valid, first_candidate, second_candidate)
                    if value < best[0]:
                        best = (value, first_candidate, second_candidate)
            step *= 0.5
        pk1_first, pk2_second = best[1], best[2]

    return MacroFitResult(
        pk1_first=pk1_first,
        pk2_second=pk2_second,
        npoints=len(valid),
        nframes=sum(point.clean_total for point in valid),
        neg_log_likelihood=macroscopic_nll(valid, pk1_first, pk2_second),
    )


# -----------------------------------------------------------------------------
# Full four-state thermodynamic model
# -----------------------------------------------------------------------------


def four_state_probabilities(
    ph: float,
    primary_pka_partner_protonated: float,
    coupled_pka_partner_protonated: float,
    coupling_shift: float,
) -> Tuple[float, float, float, float]:
    """
    Return probabilities in the order HH, primary-/coupledH,
    primaryH/coupled-, and --.

    The two base pKa values are residue-specific conditional values when
    the partner residue is protonated.  The common thermodynamic coupling
    shift changes either site's pKa when the partner is deprotonated.
    """
    ln10 = math.log(10.0)
    log_weights = (
        0.0,
        ln10 * (ph - primary_pka_partner_protonated),
        ln10 * (ph - coupled_pka_partner_protonated),
        ln10
        * (
            2.0 * ph
            - primary_pka_partner_protonated
            - coupled_pka_partner_protonated
            - coupling_shift
        ),
    )
    normalization = logsumexp(log_weights)
    return tuple(math.exp(value - normalization) for value in log_weights)  # type: ignore[return-value]


def four_state_nll(
    points: Sequence[CoupledPoint],
    primary_pka: float,
    coupled_pka: float,
    coupling_shift: float,
) -> float:
    nll = 0.0
    for point in points:
        probabilities = four_state_probabilities(
            point.ph, primary_pka, coupled_pka, coupling_shift
        )
        counts = (
            point.both_protonated,
            point.primary_deprotonated,
            point.coupled_deprotonated,
            point.both_deprotonated,
        )
        nll -= sum(
            count * safe_log_probability(probability)
            for count, probability in zip(counts, probabilities)
        )
    return nll


def fit_four_state(
    points: Sequence[CoupledPoint],
    interacting: bool,
    initial_primary_pka: Optional[float] = None,
    initial_coupled_pka: Optional[float] = None,
) -> FourStateFitResult:
    valid = [point for point in points if point.clean_total > 0]
    if len(valid) < 3:
        raise RuntimeError("Fewer than three valid pH points for four-state fit")

    ph_min = min(point.ph for point in valid)
    ph_max = max(point.ph for point in valid)
    primary_start = (
        initial_primary_pka
        if initial_primary_pka is not None and math.isfinite(initial_primary_pka)
        else 0.5 * (ph_min + ph_max)
    )
    coupled_start = (
        initial_coupled_pka
        if initial_coupled_pka is not None and math.isfinite(initial_coupled_pka)
        else 0.5 * (ph_min + ph_max)
    )
    lower_bound = ph_min - 6.0
    upper_bound = ph_max + 6.0

    converged = True
    try:
        from scipy.optimize import minimize

        if interacting:
            starts = (
                [primary_start, coupled_start, 0.0],
                [primary_start, coupled_start, 1.0],
                [primary_start, coupled_start, -1.0],
                [coupled_start, primary_start, 0.0],
            )
            best_result = None
            for start in starts:
                result = minimize(
                    lambda values: four_state_nll(
                        valid, float(values[0]), float(values[1]), float(values[2])
                    ),
                    start,
                    method="L-BFGS-B",
                    bounds=(
                        (lower_bound, upper_bound),
                        (lower_bound, upper_bound),
                        (-10.0, 10.0),
                    ),
                    options={"maxiter": 5000, "ftol": 1.0e-12, "gtol": 1.0e-8},
                )
                if best_result is None or float(result.fun) < float(best_result.fun):
                    best_result = result
            assert best_result is not None
            primary_pka = float(best_result.x[0])
            coupled_pka = float(best_result.x[1])
            coupling_shift = float(best_result.x[2])
            converged = bool(best_result.success)
        else:
            result = minimize(
                lambda values: four_state_nll(
                    valid, float(values[0]), float(values[1]), 0.0
                ),
                [primary_start, coupled_start],
                method="L-BFGS-B",
                bounds=((lower_bound, upper_bound), (lower_bound, upper_bound)),
                options={"maxiter": 5000, "ftol": 1.0e-12, "gtol": 1.0e-8},
            )
            primary_pka = float(result.x[0])
            coupled_pka = float(result.x[1])
            coupling_shift = 0.0
            converged = bool(result.success)
    except Exception:
        # Coordinate-descent fallback.  This is slower but keeps the script
        # usable if SciPy is unavailable.
        primary_pka = primary_start
        coupled_pka = coupled_start
        coupling_shift = 0.0
        best_nll = four_state_nll(valid, primary_pka, coupled_pka, coupling_shift)
        pka_step = 1.0
        coupling_step = 1.0
        for _ in range(24):
            primary_candidates = [
                primary_pka + offset * pka_step for offset in range(-3, 4)
            ]
            coupled_candidates = [
                coupled_pka + offset * pka_step for offset in range(-3, 4)
            ]
            shift_candidates = (
                [coupling_shift + offset * coupling_step for offset in range(-3, 4)]
                if interacting
                else [0.0]
            )
            for primary_candidate in primary_candidates:
                for coupled_candidate in coupled_candidates:
                    for shift_candidate in shift_candidates:
                        value = four_state_nll(
                            valid,
                            primary_candidate,
                            coupled_candidate,
                            shift_candidate,
                        )
                        if value < best_nll:
                            best_nll = value
                            primary_pka = primary_candidate
                            coupled_pka = coupled_candidate
                            coupling_shift = shift_candidate
            pka_step *= 0.5
            coupling_step *= 0.5
        converged = True

    nll = four_state_nll(valid, primary_pka, coupled_pka, coupling_shift)
    parameter_count = 3 if interacting else 2
    return FourStateFitResult(
        model="interacting" if interacting else "independent",
        primary_pka_partner_protonated=primary_pka,
        coupled_pka_partner_protonated=coupled_pka,
        coupling_shift=coupling_shift,
        npoints=len(valid),
        nframes=sum(point.clean_total for point in valid),
        neg_log_likelihood=nll,
        aic=2.0 * parameter_count + 2.0 * nll,
        converged=converged,
    )


def derived_macroscopic_from_four_state(
    fit: FourStateFitResult,
    primary_correction: float = 0.0,
    coupled_correction: float = 0.0,
) -> Tuple[float, float]:
    """Derive pair-level pK1/pK2 using optionally corrected site pKa values."""
    primary_pka = fit.primary_pka_partner_protonated + primary_correction
    coupled_pka = fit.coupled_pka_partner_protonated + coupled_correction
    # pK1 is the first protonation from the doubly deprotonated state.
    maximum = max(primary_pka, coupled_pka)
    log10_sum = maximum + math.log10(
        10.0 ** (primary_pka - maximum) + 10.0 ** (coupled_pka - maximum)
    )
    pk1_first = fit.coupling_shift + log10_sum
    pk2_second = primary_pka + coupled_pka + fit.coupling_shift - pk1_first
    return pk1_first, pk2_second


def coupling_free_energy_kcal_mol(
    coupling_shift: float,
    temperature_k: float,
) -> float:
    gas_constant = 0.00198720425864083  # kcal mol^-1 K^-1
    return math.log(10.0) * gas_constant * temperature_k * coupling_shift


def fitted_p1_carrier_fractions(
    fit: FourStateFitResult,
) -> Tuple[float, float]:
    """
    Fractions of the singly protonated ensemble in which the primary or
    coupled residue carries the proton.  In this four-state model the ratio
    is independent of pH.
    """
    # primary protonated / coupled deprotonated has weight 10^(pH-pKa_coupled)
    # primary deprotonated / coupled protonated has weight 10^(pH-pKa_primary)
    log_primary_holds = -fit.coupled_pka_partner_protonated * math.log(10.0)
    log_coupled_holds = -fit.primary_pka_partner_protonated * math.log(10.0)
    normalization = logsumexp((log_primary_holds, log_coupled_holds))
    return (
        math.exp(log_primary_holds - normalization),
        math.exp(log_coupled_holds - normalization),
    )


def empirical_p1_carrier_fractions(
    points: Sequence[CoupledPoint],
) -> Tuple[float, float]:
    primary_holds = sum(point.coupled_deprotonated for point in points)
    coupled_holds = sum(point.primary_deprotonated for point in points)
    total = primary_holds + coupled_holds
    if total == 0:
        return math.nan, math.nan
    return primary_holds / total, coupled_holds / total


def classify_carrier_assignment(
    primary_fraction: float,
    coupled_fraction: float,
    threshold: float,
    primary_label: str,
    coupled_label: str,
) -> str:
    if not math.isfinite(primary_fraction) or not math.isfinite(coupled_fraction):
        return "undetermined"
    if primary_fraction >= threshold:
        return f"{primary_label}-dominant"
    if coupled_fraction >= threshold:
        return f"{coupled_label}-dominant"
    return "shared"


def fit_coupled_core(
    points: Sequence[CoupledPoint],
    args: argparse.Namespace,
) -> CoupledFullResult:
    """Fit only the macroscopic and four-state models.

    This lighter path is used for block, convergence, and cutoff-sensitivity
    scans so hundreds of short windows do not each trigger six additional
    nonlinear HH fits.
    """
    macro = fit_macroscopic(points)
    independent = fit_four_state(points, interacting=False)
    interacting = fit_four_state(
        points,
        interacting=True,
        initial_primary_pka=independent.primary_pka_partner_protonated,
        initial_coupled_pka=independent.coupled_pka_partner_protonated,
    )
    empirical_primary, empirical_coupled = empirical_p1_carrier_fractions(points)
    fitted_primary, fitted_coupled = fitted_p1_carrier_fractions(interacting)
    assignment = classify_carrier_assignment(
        fitted_primary,
        fitted_coupled,
        args.assignment_threshold,
        args.primary_label,
        args.coupled_label,
    )
    return CoupledFullResult(
        macro=macro,
        independent=independent,
        interacting=interacting,
        marginal_fits={},
        conditional_fits={},
        empirical_primary_protonated_fraction_in_p1=empirical_primary,
        empirical_coupled_protonated_fraction_in_p1=empirical_coupled,
        fitted_primary_protonated_fraction_in_p1=fitted_primary,
        fitted_coupled_protonated_fraction_in_p1=fitted_coupled,
        assignment=assignment,
        delta_aic_independent_minus_interacting=independent.aic - interacting.aic,
        likelihood_ratio_statistic=2.0
        * (independent.neg_log_likelihood - interacting.neg_log_likelihood),
    )


def fit_complete_coupled_analysis(
    points: Sequence[CoupledPoint],
    args: argparse.Namespace,
) -> CoupledFullResult:
    curves = coupled_curve_sets(points, args.primary_label, args.coupled_label)
    fits = fit_grouped(curves, args.fit_method, args.hill)
    marginal_labels = {
        f"{args.primary_label}_marginal",
        f"{args.coupled_label}_marginal",
    }
    marginal_fits = {key: value for key, value in fits.items() if key in marginal_labels}
    conditional_fits = {key: value for key, value in fits.items() if key not in marginal_labels}

    primary_initial = marginal_fits.get(f"{args.primary_label}_marginal")
    coupled_initial = marginal_fits.get(f"{args.coupled_label}_marginal")
    macro = fit_macroscopic(points)
    independent = fit_four_state(
        points,
        interacting=False,
        initial_primary_pka=primary_initial.pka if primary_initial else None,
        initial_coupled_pka=coupled_initial.pka if coupled_initial else None,
    )
    interacting = fit_four_state(
        points,
        interacting=True,
        initial_primary_pka=independent.primary_pka_partner_protonated,
        initial_coupled_pka=independent.coupled_pka_partner_protonated,
    )

    empirical_primary, empirical_coupled = empirical_p1_carrier_fractions(points)
    fitted_primary, fitted_coupled = fitted_p1_carrier_fractions(interacting)
    assignment = classify_carrier_assignment(
        fitted_primary,
        fitted_coupled,
        args.assignment_threshold,
        args.primary_label,
        args.coupled_label,
    )
    return CoupledFullResult(
        macro=macro,
        independent=independent,
        interacting=interacting,
        marginal_fits=marginal_fits,
        conditional_fits=conditional_fits,
        empirical_primary_protonated_fraction_in_p1=empirical_primary,
        empirical_coupled_protonated_fraction_in_p1=empirical_coupled,
        fitted_primary_protonated_fraction_in_p1=fitted_primary,
        fitted_coupled_protonated_fraction_in_p1=fitted_coupled,
        assignment=assignment,
        delta_aic_independent_minus_interacting=independent.aic - interacting.aic,
        likelihood_ratio_statistic=2.0
        * (independent.neg_log_likelihood - interacting.neg_log_likelihood),
    )


