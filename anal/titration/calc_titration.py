#!/usr/bin/env python3
"""
calc_titration.py

Analysis of Amber CpHMD lambda trajectories with special support for a
coupled two-site titration pair.

Coupled-mode design
-------------------
The coupled analysis follows the hierarchy used in Shen-group CpHMD work:

1. Count the four clean joint protonation states at each pH.
2. Fit the pair-level macroscopic stepwise pKa values pK1 and pK2 from the
   zero-, one-, and two-proton populations.  pK1 is the first protonation
   event from the doubly deprotonated state and pK2 is the second event.
   The fit enforces pK1 >= pK2.
3. Fit residue-specific marginal and conditional titration curves.
4. Fit the complete four-state thermodynamic model, both with and without
   an explicit coupling parameter.  This produces residue-assigned
   conditional pKa values and a formal independent-versus-coupled model
   comparison.
5. Report block, bootstrap, convergence, and optional cutoff-sensitivity
   diagnostics.

When --coupled is used, every output generated by the invocation is routed
into --coupled-output-dir (default: coupled_anal), regardless of any output
path supplied on the command line.  Only the basename of a user-supplied
output path is retained.  This prevents the analysis from polluting the
simulation directory.

The script preserves ordinary single-site and histidine analysis modes from
lambda_to_titcurve_stats2.py.
"""

