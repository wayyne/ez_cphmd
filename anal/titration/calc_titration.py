def read_lambda_lines(path: str) -> Tuple[List[str], List[str], List[List[str]]]:
    ires: List[str] = []
    itauto: List[str] = []
    data: List[List[str]] = []
    expected_columns: Optional[int] = None

    with open(path, "r") as handle:
        for raw_line in handle:
            line = raw_line.strip()
            if not line:
                continue
            parts = line.split()
            if parts[0] == "#":
                if len(parts) >= 3 and parts[1] == "ititr":
                    expected_columns = len(parts) - 2
                elif len(parts) >= 3 and parts[1] == "ires":
                    ires = parts[2:]
                elif len(parts) >= 3 and parts[1] == "itauto":
                    itauto = parts[2:]
                continue
            data.append(parts)

    if expected_columns is not None and ires:
        if len(ires) != expected_columns:
            compact = "".join(ires)
            if not compact.isdigit():
                raise RuntimeError(
                    f"Malformed compact ires header in {path}: residue IDs "
                    "must contain only digits."
                )
            if len(compact) % expected_columns != 0:
                raise RuntimeError(
                    f"Cannot split compact ires header in {path}: {len(compact)} "
                    f"digits for {expected_columns} columns."
                )
            width = len(compact) // expected_columns
            ires = [compact[i : i + width] for i in range(0, len(compact), width)]

        if len(ires) != expected_columns:
            raise RuntimeError(
                f"ires column count mismatch in {path}: expected "
                f"{expected_columns}, found {len(ires)}."
            )
        if itauto and len(itauto) != expected_columns:
            raise RuntimeError(
                f"itauto column count mismatch in {path}: expected "
                f"{expected_columns}, found {len(itauto)}."
            )

    return ires, itauto, data


def _residue_matches(value: str, resid: str) -> bool:
    try:
        return int(float(value)) == int(float(resid))
    except ValueError:
        return value == resid


def select_protonation_column(
    ires: Sequence[str],
    itauto: Sequence[str],
    resid: str,
) -> Optional[int]:
    """
    Return the one-based data column for the protonation coordinate.

    Amber CpHMD lambda files can contain multiple coordinates for the same
    titratable residue.  The relevant itauto conventions in these data are:

      itauto = 1 : His protonation lambda
      itauto = 2 : His tautomer coordinate
      itauto = 3 : Asp/Glu carboxylate protonation lambda
      itauto = 4 : Asp/Glu carboxylate tautomer coordinate

    For duplicated residue entries, explicitly select the protonation
    coordinate rather than relying on column order.  Carboxylate
    protonation (itauto=3) is preferred when present; otherwise His-style
    protonation (itauto=1) is accepted.

    If a residue occurs only once, that column is returned directly.

    If a duplicated residue cannot be assigned unambiguously from itauto,
    fail loudly rather than silently selecting the first occurrence.
    """
    candidates = [
        index
        for index, value in enumerate(ires)
        if _residue_matches(value, resid)
    ]

    if not candidates:
        return None

    if len(candidates) == 1:
        return candidates[0] + 1

    candidate_flags: Dict[int, Optional[int]] = {}

    for index in candidates:
        flag: Optional[int] = None

        if index < len(itauto):
            try:
                flag = int(float(itauto[index]))
            except (ValueError, TypeError):
                flag = None

        candidate_flags[index] = flag

    # Asp/Glu carboxylates in the HEWL lambda files:
    # itauto=3 is protonation lambda; itauto=4 is tautomer.
    matches_itauto3 = [
        index
        for index in candidates
        if candidate_flags[index] == 3
    ]

    if len(matches_itauto3) == 1:
        return matches_itauto3[0] + 1

    if len(matches_itauto3) > 1:
        raise RuntimeError(
            f"Residue {resid} has multiple itauto=3 protonation "
            f"coordinates at columns "
            f"{[index + 1 for index in matches_itauto3]}"
        )

    # Retain support for residue types whose protonation coordinate uses
    # the itauto=1 convention.
    matches_itauto1 = [
        index
        for index in candidates
        if candidate_flags[index] == 1
    ]

    if len(matches_itauto1) == 1:
        return matches_itauto1[0] + 1

    if len(matches_itauto1) > 1:
        raise RuntimeError(
            f"Residue {resid} has multiple itauto=1 protonation "
            f"coordinates at columns "
            f"{[index + 1 for index in matches_itauto1]}"
        )

    details = ", ".join(
        f"column {index + 1}: itauto={candidate_flags[index]}"
        for index in candidates
    )

    raise RuntimeError(
        f"Could not identify the protonation coordinate for duplicated "
        f"residue {resid}. Candidate columns: {details}. "
        "Expected a unique itauto=3 carboxylate protonation coordinate "
        "or a unique itauto=1 protonation coordinate."
    )

def select_his_columns(
    ires: Sequence[str],
    itauto: Sequence[str],
    resid: str,
) -> Tuple[Optional[int], Optional[int]]:
    lambda_column = None
    chi_column = None
    for index, value in enumerate(ires):
        if not _residue_matches(value, resid):
            continue
        tautomer_flag = None
        if index < len(itauto):
            try:
                tautomer_flag = int(float(itauto[index]))
            except ValueError:
                tautomer_flag = None
        if tautomer_flag == 1:
            lambda_column = index + 1
        elif tautomer_flag == 2:
            chi_column = index + 1
    return lambda_column, chi_column


def _make_prefix_cache(
    path: str,
    ph: float,
    mode: str,
    times_ns: List[float],
    state_codes: List[int],
    nstates: int,
) -> CachedLambdaFile:
    if not times_ns:
        raise RuntimeError(f"No readable lambda data rows in {path}")

    if any(times_ns[index] < times_ns[index - 1] for index in range(1, len(times_ns))):
        ordered = sorted(zip(times_ns, state_codes), key=lambda item: item[0])
        times_ns = [item[0] for item in ordered]
        state_codes = [item[1] for item in ordered]

    prefixes: List[List[int]] = [[0] for _ in range(nstates)]
    for code in state_codes:
        for state in range(nstates):
            prefixes[state].append(prefixes[state][-1] + int(code == state))

    return CachedLambdaFile(
        path=path,
        ph=ph,
        mode=mode,
        times_ns=tuple(times_ns),
        prefixes=tuple(tuple(prefix) for prefix in prefixes),
    )


def build_residue_cache(
    path: str,
    resid: str,
    dt_ps: float,
    low: float,
    high: float,
) -> CachedLambdaFile:
    ph = parse_ph_from_filename(path)
    ires, itauto, data = read_lambda_lines(path)
    lambda_column = select_protonation_column(ires, itauto, resid)
    if lambda_column is None:
        raise RuntimeError(f"Could not find protonation coordinate for residue {resid} in {path}")

    first_step: Optional[float] = None
    times_ns: List[float] = []
    state_codes: List[int] = []
    for parts in data:
        if len(parts) <= lambda_column:
            continue
        try:
            step = float(parts[0])
            lam = float(parts[lambda_column])
        except ValueError:
            continue
        if first_step is None:
            first_step = step
        time_ns = (step - first_step) * dt_ps / 1000.0
        if lam <= low:
            code = 0
        elif lam >= high:
            code = 1
        else:
            code = 2
        times_ns.append(time_ns)
        state_codes.append(code)

    return _make_prefix_cache(path, ph, "normal", times_ns, state_codes, 3)


def build_his_cache(path: str, args: argparse.Namespace) -> CachedLambdaFile:
    ph = parse_ph_from_filename(path)
    ires, itauto, data = read_lambda_lines(path)
    lambda_column, chi_column = select_his_columns(ires, itauto, args.his_resid)
    if lambda_column is None or chi_column is None:
        raise RuntimeError(
            f"Could not find His residue {args.his_resid} with itauto 1 and 2 in {path}"
        )

    first_step: Optional[float] = None
    times_ns: List[float] = []
    state_codes: List[int] = []
    for parts in data:
        if len(parts) <= max(lambda_column, chi_column):
            continue
        try:
            step = float(parts[0])
            lam = float(parts[lambda_column])
            chi = float(parts[chi_column])
        except ValueError:
            continue
        if first_step is None:
            first_step = step
        time_ns = (step - first_step) * args.dt_ps / 1000.0

        if lam <= args.low:
            code = 0
        elif lam >= args.high:
            if chi <= args.low:
                code = 1
            elif chi >= args.high:
                code = 2
            else:
                code = 3
        else:
            code = 4
        times_ns.append(time_ns)
        state_codes.append(code)

    return _make_prefix_cache(path, ph, "his", times_ns, state_codes, 5)


def classify_coupled_state(
    primary_lambda: float,
    coupled_lambda: float,
    low: float,
    high: float,
) -> int:
    """
    Classify one two-site lambda observation.

    State codes:
      0 = S2: both protonated
      1 = S1_coupled: primary deprotonated, coupled protonated
      2 = S1_primary: primary protonated, coupled deprotonated
      3 = S0: both deprotonated
      4 = mixed: at least one lambda lies between the clean-state cutoffs
    """
    primary_protonated = primary_lambda <= low
    primary_deprotonated = primary_lambda >= high
    coupled_protonated = coupled_lambda <= low
    coupled_deprotonated = coupled_lambda >= high

    if primary_protonated and coupled_protonated:
        return 0
    if primary_deprotonated and coupled_protonated:
        return 1
    if primary_protonated and coupled_deprotonated:
        return 2
    if primary_deprotonated and coupled_deprotonated:
        return 3
    return 4


def coupled_state_label(
    code: int,
    primary_label: str,
    coupled_label: str,
) -> str:
    labels = {
        0: "S2",
        1: f"S1_{coupled_label}",
        2: f"S1_{primary_label}",
        3: "S0",
        4: "mixed",
    }
    return labels[code]

def build_coupled_cache(
    path: str,
    primary_resid: str,
    coupled_resid: str,
    dt_ps: float,
    low: float,
    high: float,
) -> CachedLambdaFile:
    ph = parse_ph_from_filename(path)
    ires, itauto, data = read_lambda_lines(path)
    primary_column = select_protonation_column(ires, itauto, primary_resid)
    coupled_column = select_protonation_column(ires, itauto, coupled_resid)
    if primary_column is None:
        raise RuntimeError(f"Could not find primary residue {primary_resid} in {path}")
    if coupled_column is None:
        raise RuntimeError(f"Could not find coupled residue {coupled_resid} in {path}")
    if primary_column == coupled_column:
        raise RuntimeError("Primary and coupled residue columns are identical")

    first_step: Optional[float] = None
    times_ns: List[float] = []
    state_codes: List[int] = []
    for parts in data:
        if len(parts) <= max(primary_column, coupled_column):
            continue
        try:
            step = float(parts[0])
            primary_lambda = float(parts[primary_column])
            coupled_lambda = float(parts[coupled_column])
        except ValueError:
            continue
        if first_step is None:
            first_step = step
        time_ns = (step - first_step) * dt_ps / 1000.0

        code = classify_coupled_state(
            primary_lambda,
            coupled_lambda,
            low,
            high,
        )
        times_ns.append(time_ns)
        state_codes.append(code)

    return _make_prefix_cache(path, ph, "coupled", times_ns, state_codes, 5)


def load_residue_caches(
    files: Sequence[str],
    resid: str,
    args: argparse.Namespace,
    low: Optional[float] = None,
    high: Optional[float] = None,
) -> List[CachedLambdaFile]:
    caches: List[CachedLambdaFile] = []
    low_value = args.low if low is None else low
    high_value = args.high if high is None else high
    for path in files:
        try:
            caches.append(
                build_residue_cache(path, resid, args.dt_ps, low_value, high_value)
            )
        except Exception as error:
            print(f"Warning: skipping {path}: {error}", file=sys.stderr)
    return caches


def load_his_caches(files: Sequence[str], args: argparse.Namespace) -> List[CachedLambdaFile]:
    caches: List[CachedLambdaFile] = []
    for path in files:
        try:
            caches.append(build_his_cache(path, args))
        except Exception as error:
            print(f"Warning: skipping {path}: {error}", file=sys.stderr)
    return caches


def load_coupled_caches(
    files: Sequence[str],
    args: argparse.Namespace,
    low: Optional[float] = None,
    high: Optional[float] = None,
) -> List[CachedLambdaFile]:
    caches: List[CachedLambdaFile] = []
    low_value = args.low if low is None else low
    high_value = args.high if high is None else high
    for path in files:
        try:
            caches.append(
                build_coupled_cache(
                    path,
                    args.resid,
                    args.coupled,
                    args.dt_ps,
                    low_value,
                    high_value,
                )
            )
        except Exception as error:
            print(f"Warning: skipping coupled analysis for {path}: {error}", file=sys.stderr)
    return caches


def _window_counts(
    cache: CachedLambdaFile,
    start_ns: float,
    end_ns: float,
) -> Tuple[int, ...]:
    left = bisect.bisect_left(cache.times_ns, start_ns)
    right = bisect.bisect_left(cache.times_ns, end_ns)
    return tuple(prefix[right] - prefix[left] for prefix in cache.prefixes)


