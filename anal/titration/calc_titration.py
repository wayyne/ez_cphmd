def write_ordinary_data_file(
    path: Path,
    grouped: Mapping[str, Sequence[CurvePoint]],
) -> None:
    with path.open("w") as handle:
        handle.write("# curve pH frac prot unprot mixed pKa_from_point_hill1\n")
        for label in sorted(grouped):
            for point in sorted(grouped[label], key=lambda item: item.ph):
                denominator = point.clean_total
                adjusted = (point.unprot + 0.5) / (denominator + 1.0)
                point_pka = point.ph - math.log10(adjusted / (1.0 - adjusted))
                handle.write(
                    f"{label} {point.ph:.6f} {point.frac:.8f} {point.prot:d} "
                    f"{point.unprot:d} {point.mixed:d} {point_pka:.6f}\n"
                )


def ordinary_block_rows(
    caches: Sequence[CachedLambdaFile],
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for block_segments in parse_int_list(args.block_segments):
        block_length = block_ns_from_segments(args, block_segments)
        nblocks = int(math.floor((end_ns - start_ns) / block_length))
        for index in range(nblocks):
            window_start = start_ns + index * block_length
            window_end = window_start + block_length
            grouped = compute_grouped(caches, args, window_start, window_end)
            fits = fit_grouped(grouped, args.fit_method, args.hill)
            for label, fit in fits.items():
                rows.append(
                    {
                        "label": label,
                        "block_segments": block_segments,
                        "block_ns": block_length,
                        "block_index": index,
                        "pKa": fit.pka,
                        "Hill": fit.hill,
                        "objective": fit.objective,
                    }
                )
    return rows


def ordinary_convergence_rows(
    caches: Sequence[CachedLambdaFile],
    args: argparse.Namespace,
    start_ns: float,
    end_ns: float,
) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    windows: List[Tuple[str, float, float]] = []
    if args.cumulative:
        current = start_ns + args.cumulative_step_ns
        while current <= end_ns + 1.0e-12:
            windows.append(("cumulative", start_ns, min(current, end_ns)))
            current += args.cumulative_step_ns
    if args.sliding_window_ns > 0.0:
        current = start_ns
        while current + args.sliding_window_ns <= end_ns + 1.0e-12:
            windows.append(("sliding", current, current + args.sliding_window_ns))
            current += args.sliding_step_ns
    for mode, window_start, window_end in windows:
        grouped = compute_grouped(caches, args, window_start, window_end)
        fits = fit_grouped(grouped, args.fit_method, args.hill)
        for label, fit in fits.items():
            rows.append(
                {
                    "mode": mode,
                    "label": label,
                    "start_ns": window_start,
                    "end_ns": window_end,
                    "pKa": fit.pka,
                    "Hill": fit.hill,
                }
            )
    return rows


def ordinary_plot(
    output: Optional[Path],
    grouped: Mapping[str, Sequence[CurvePoint]],
    fits: Mapping[str, FitResult],
) -> None:
    if output is None:
        return
    try:
        import matplotlib.pyplot as plt
    except Exception as error:
        print(f"Warning: matplotlib unavailable; skipping plot: {error}", file=sys.stderr)
        return
    figure, axis = plt.subplots(figsize=(8.0, 6.0))
    all_ph: List[float] = []
    for label, points in grouped.items():
        points = sorted(points, key=lambda point: point.ph)
        x_values = [point.ph for point in points]
        y_values = [point.frac for point in points]
        all_ph.extend(x_values)
        axis.scatter(x_values, y_values, label=f"{label} data")
        fit = fits.get(label)
        if fit:
            grid = [
                min(x_values) + (max(x_values) - min(x_values)) * index / 200.0
                for index in range(201)
            ]
            axis.plot(
                grid,
                [hh_function(ph, fit.pka, fit.hill) for ph in grid],
                label=f"{label} fit pKa={fit.pka:.2f}, Hill={fit.hill:.2f}",
            )
    axis.set_xlabel("pH")
    axis.set_ylabel("Unprotonated fraction")
    axis.set_ylim(-0.02, 1.02)
    if all_ph:
        axis.set_xlim(min(all_ph) - 0.25, max(all_ph) + 0.25)
    axis.legend()
    figure.tight_layout()
    figure.savefig(output, dpi=200)
    plt.close(figure)


