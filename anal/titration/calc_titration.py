def validate_args(args: argparse.Namespace) -> None:
    if args.dt_fs is not None:
        args.dt_ps = args.dt_fs / 1000.0
    args.start_ns, args.end_ns = parse_time_window(args.time)
    if args.end_ns <= args.start_ns:
        raise SystemExit("Error: analysis end time must exceed start time")
    if not (0.0 <= args.low < args.high <= 1.0):
        raise SystemExit("Error: lambda cutoffs must satisfy 0 <= low < high <= 1")
    if args.resid is not None and args.his_resid is not None:
        raise SystemExit("Error: use either -R/--resid or -H/--his-resid, not both")
    if args.coupled is not None and args.resid is None:
        raise SystemExit("Error: --coupled requires -R/--resid")
    if args.coupled is not None and args.his_resid is not None:
        raise SystemExit("Error: --coupled cannot be combined with --his-resid")
    if args.coupled is not None and _residue_matches(args.coupled, args.resid):
        raise SystemExit("Error: --coupled must identify a different residue")
    if args.nboot <= 0:
        raise SystemExit("Error: --nboot must be positive")
    if args.jobs < 0:
        raise SystemExit("Error: --jobs must be zero or positive")
    if args.bootstrap_chunk_size <= 0:
        raise SystemExit("Error: --bootstrap-chunk-size must be positive")
    if not (0.5 < args.assignment_threshold <= 1.0):
        raise SystemExit("Error: --assignment-threshold must be >0.5 and <=1")
    if args.temperature_k <= 0.0:
        raise SystemExit("Error: --temperature-k must be positive")
    if args.coupled is not None:
        if args.primary_label is None:
            args.primary_label = f"res{args.resid}"
        if args.coupled_label is None:
            args.coupled_label = f"res{args.coupled}"
    else:
        args.primary_label = args.primary_label or (
            f"res{args.resid}" if args.resid is not None else "residue"
        )
    parse_int_list(args.block_segments)
    parse_cutoff_pairs(args.coupled_cutoff_sensitivity)


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    validate_args(args)
    if args.coupled is not None:
        return run_coupled_mode(args)
    return run_ordinary_mode(args)


if __name__ == "__main__":
    sys.exit(main())